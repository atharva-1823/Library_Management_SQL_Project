-- Q6. Create a new table that contains: book ISBN,book title,total number of times the book was issued
create table issued_book_count as 
select b.isbn,b.book_title,count(ist.issued_id) as issued_count
from issued_status ist
join books b
on ist.issued_book_isbn=b.isbn
group by b.isbn,b.book_title;

select * from issued_book_count;

-- Q7. Retrieve all books that belong to the category "Classic".
select * from  books
