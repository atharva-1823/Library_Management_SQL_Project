-- Q10. Display employees with their branch manager's name and branch details.
select e.*,
	   b.branch_id,
       e2.emp_name as manager
from employees e
join branch b 
on e.branch_id=b.branch_id
join employees e2
on b.manager_id=e2.emp_id;

